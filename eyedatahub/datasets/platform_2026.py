"""Platform discovery additions from the July 2026 repository search.

This module indexes datasets found during a targeted pass over Mendeley Data,
Zenodo, Kaggle, Hugging Face, PhysioNet, and Grand Challenge. Several entries
are derivative annotation layers or VQA/text views built from existing image
datasets; those are retained only when they expose a distinct research surface
and are flagged in ``notes``.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, List, Union

from eyedatahub.core.dataset import DatasetInfo, DatasetSample, EyeDataHubDataset
from eyedatahub.datasets.download_utils import (
    download_figshare,
    download_dryad,
    download_github_repo,
    download_huggingface,
    download_kaggle,
    download_mendeley,
    download_physionet,
    download_zenodo,
    print_manual_download_instructions,
)


class PlatformDiscoveryDataset(EyeDataHubDataset):
    """Small metadata-only dataset wrapper for platform-discovered entries."""

    def __init__(self, record: dict[str, Any]) -> None:
        self.record = record
        self._SUBDIR = record["name"]

    @property
    def info(self) -> DatasetInfo:
        r = self.record
        return DatasetInfo(
            name=r["name"],
            full_name=r["full_name"],
            description=r["description"],
            modality=r["modality"],
            tasks=r["tasks"],
            num_samples=r.get("num_samples"),
            splits=r.get("splits", ["all"]),
            classes=r.get("classes"),
            num_classes=r.get("num_classes"),
            download_type=r["download_type"],
            download_url=r["download_url"],
            license=r.get("license", "Unknown"),
            citation=r.get("citation", ""),
            tags=r.get("tags", []),
            size_gb=r.get("size_gb"),
            notes=r.get("notes", ""),
        )

    def is_downloaded(self, data_dir: Union[str, Path]) -> bool:
        root = Path(data_dir).expanduser() / self._SUBDIR
        if self.sentinel_path(data_dir).exists():
            return True
        ignored = {".download_complete", "eyedatahub-acquisition-manifest.json"}
        return root.exists() and any(
            path.is_file() and path.name not in ignored for path in root.rglob("*")
        )

    def download(self, data_dir: Union[str, Path]) -> None:
        dest = Path(data_dir).expanduser() / self._SUBDIR
        source = self.record.get("source", {})
        dtype = self.info.download_type

        if dtype == "mendeley":
            download_mendeley(source["id"], source["version"], dest)
        elif dtype == "zenodo":
            download_zenodo(source["record"], dest)
        elif dtype == "huggingface":
            download_huggingface(source["repo"], dest, repo_type="dataset")
        elif dtype == "github":
            download_github_repo(source["repo"], dest, branch=source.get("branch", "main"))
        elif dtype == "figshare":
            download_figshare(source["id"], dest)
        elif dtype == "dryad":
            download_dryad(source["doi"], dest)
        elif dtype == "kaggle":
            download_kaggle(
                source["dataset"],
                dest,
                is_competition=source.get("is_competition", False),
            )
        elif dtype == "physionet":
            download_physionet(
                source["slug"],
                source["version"],
                dest,
                credentialed=source.get("credentialed", False),
            )
        else:
            print_manual_download_instructions(
                self.info.full_name,
                self.info.download_url or "",
                dest,
                extra_notes=self.info.notes,
            )

    def load(self, data_dir: Union[str, Path], split: str = "test") -> List[DatasetSample]:
        raise NotImplementedError(
            f"{self.info.name} is currently registered for discovery/access metadata. "
            "Dataset-specific parser support is not implemented yet."
        )


